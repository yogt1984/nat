def find_parquet_files(data_dir: Path, hours: Optional[int] = None) -> list:
    """Find Parquet files, optionally filtered by age.

    If ``data_dir`` points at a single ``.parquet`` file, that file is returned
    verbatim (the ``--hours`` age filter does not apply to an explicitly named
    file). Otherwise the directory is scanned recursively.
    """
    if data_dir.is_file():
        return [data_dir]

    files = list(data_dir.rglob("*.parquet"))

    if hours:
        cutoff = datetime.now() - timedelta(hours=hours)
        filtered = []
        for f in files:
            # Try to extract date from path (YYYY-MM-DD/file.parquet)
            try:
                date_str = f.parent.name
                file_date = datetime.strptime(date_str, "%Y-%m-%d")
                if file_date >= cutoff.replace(hour=0, minute=0, second=0):
                    filtered.append(f)
            except ValueError:
                # Can't parse date, include anyway
                filtered.append(f)
        files = filtered

    return sorted(files)


def load_data(files: list) -> pd.DataFrame:
    """Load and concatenate Parquet files."""
    if not files:
        return pd.DataFrame()

    dfs = []
    for f in files:
        try:
            df = pq.read_table(f).to_pandas()
            dfs.append(df)
        except Exception as e:
            print(f"  Warning: Could not read {f}: {e}")

    if not dfs:
        return pd.DataFrame()

    return pd.concat(dfs, ignore_index=True)


