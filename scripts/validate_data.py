#!/usr/bin/env python3
"""
Data Validation Script for ING Feature Data

Validates Parquet files generated by the ingestor:
- Continuity: No gaps larger than threshold
- Distributions: Features within expected ranges
- NaN ratio: Less than threshold after warmup
- File integrity: All files readable
- Cross-symbol consistency: Similar row counts across symbols

Usage:
    python scripts/validate_data.py [DATA_DIR] [--verbose] [--hours N]

Examples:
    python scripts/validate_data.py                    # Validate default directory
    python scripts/validate_data.py ./data/features   # Validate specific directory
    python scripts/validate_data.py --hours 24        # Only last 24 hours
    python scripts/validate_data.py --verbose         # Show detailed output
"""

import argparse
import json as _json
import sys
from dataclasses import dataclass, field
from datetime import datetime, timedelta
from pathlib import Path
from typing import Optional

import numpy as np
import pyarrow.parquet as pq
import pandas as pd


# =============================================================================
# Configuration
# =============================================================================

@dataclass
class ValidationConfig:
    """Validation thresholds and settings."""
    # Continuity
    max_gap_seconds: float = 5.0          # Max allowed gap between records
    min_records_per_hour: int = 30000     # Expected ~36000 at 100ms (10/sec * 3600)

    # NaN handling
    max_nan_ratio: float = 0.01           # Max 1% NaN after warmup
    warmup_seconds: int = 60              # Ignore first 60s for NaN check

    # Feature ranges (will flag if outside)
    feature_ranges: dict = field(default_factory=lambda: {
        'midprice': (0.001, 1_000_000),       # Price must be positive
        'spread_bps': (0, 1000),               # Spread 0-10%
        'qty_l1': (-1, 1),                     # Imbalance -1 to 1
        'returns_1m': (-1, 1),                 # Vol reasonable
        'vpin_10': (0, 1),                     # VPIN 0-1
        'kyle_lambda_100': (-1e6, 1e6),        # Lambda can vary
    })

    # Cross-symbol
    max_count_ratio_diff: float = 0.1     # Max 10% difference in row counts

    # Category liveness (BUG-6). A category whose every column is 100% NaN means a
    # subsystem stopped computing — categorically different from scattered NaN, which
    # is `NaN Ratio`'s job.
    #
    # The declared-dead set is DECLARED, never inferred from a threshold, and it is
    # short on purpose. Only `hm` (heatmap, 8 features) qualifies: a per-category
    # census over all 76 day-directories found 0/53 days with a single finite value.
    #
    # A raw alive/total ratio is NOT the right instrument here and must not be used as
    # one. `whale` 36/76 and `concentration` 36/76 look half-dead by that count, but the
    # count is dominated by April-to-mid-June, before the position tracker was deployed
    # at all. Split at the 06-18 deploy and they are healthy:
    #
    #     since 2026-06-18       alive / dead      dead days
    #     whale                    35 / 3          06-19, 08-04, 08-09
    #     concentration            35 / 3          06-19, 08-04, 08-09
    #     liquidation              34 / 4          06-19, 07-27, 08-04, 08-09
    #     regime                   23 / 15         contiguous DEAD since 07-26
    #
    # So there is exactly one standing regression (`regime`), not four. The scattered
    # dead days for the position-tracker trio are all low-coverage days — the same days
    # on which no continuous run reaches these categories' readiness windows — which is
    # a symptom of ingestion continuity, not of those categories being broken.
    #
    # Adding a prefix here says "this subsystem is known to be off forever", which
    # should cost an edit and a justification rather than happen silently.
    expected_dead_categories: frozenset = frozenset({"hm"})


# =============================================================================
# Validation Results
# =============================================================================

# Checks whose failure is a hard FAIL (data is unusable). Any other failing
# check is a soft WARN. Used to derive the three-level verdict (PASS/WARN/FAIL).
HARD_CHECKS = frozenset({
    "Data Presence",
    "File Integrity",
    "Continuity",
    "NaN Ratio",
    "Category Liveness",
    "Sequence Monotonicity",
})


@dataclass
class CheckResult:
    """Result of a single validation check."""
    name: str
    passed: bool
    message: str
    details: Optional[dict] = None


@dataclass
class ValidationReport:
    """Full validation report."""
    data_dir: str
    timestamp: datetime
    total_files: int
    total_rows: int
    symbols: list
    date_range: tuple
    checks: list

    @property
    def passed(self) -> bool:
        return all(c.passed for c in self.checks)

    @property
    def verdict(self) -> str:
        """Three-level verdict: FAIL if any hard check fails, else WARN if any
        soft check fails, else PASS."""
        if any(not c.passed and c.name in HARD_CHECKS for c in self.checks):
            return "FAIL"
        if any(not c.passed for c in self.checks):
            return "WARN"
        return "PASS"

    def to_dict(self) -> dict:
        """Machine-readable report (JSON-serializable)."""
        return {
            "data_dir": self.data_dir,
            "timestamp": self.timestamp.strftime("%Y-%m-%d %H:%M:%S"),
            "verdict": self.verdict,
            "passed": self.passed,
            "total_files": self.total_files,
            "total_rows": self.total_rows,
            "symbols": self.symbols,
            "date_range": list(self.date_range),
            "checks": [
                {
                    "name": c.name,
                    "passed": c.passed,
                    "hard": c.name in HARD_CHECKS,
                    "message": c.message,
                    "details": c.details,
                }
                for c in self.checks
            ],
        }

    def print_report(self, verbose: bool = False):
        """Print formatted report."""
        print("\n" + "=" * 70)
        print("               ING DATA VALIDATION REPORT")
        print("=" * 70)
        print(f"  Data Directory: {self.data_dir}")
        print(f"  Report Time:    {self.timestamp.strftime('%Y-%m-%d %H:%M:%S')}")
        print(f"  Files Scanned:  {self.total_files}")
        print(f"  Total Rows:     {self.total_rows:,}")
        print(f"  Symbols:        {', '.join(self.symbols)}")
        if self.date_range[0] and self.date_range[1]:
            print(f"  Date Range:     {self.date_range[0]} to {self.date_range[1]}")
        print("=" * 70)
        print("\n  CHECK RESULTS:\n")

        for check in self.checks:
            status = "\033[92mPASS\033[0m" if check.passed else "\033[91mFAIL\033[0m"
            print(f"  [{status}] {check.name}")
            print(f"         {check.message}")
            if verbose and check.details:
                for k, v in check.details.items():
                    print(f"         - {k}: {v}")
            print()

        print("=" * 70)
        verdict = self.verdict
        if verdict == "PASS":
            print("  \033[92mOVERALL: PASS — all checks passed\033[0m")
        elif verdict == "WARN":
            warned = [c.name for c in self.checks if not c.passed]
            print(f"  \033[93mOVERALL: WARN — {len(warned)} soft check(s) flagged\033[0m")
            print(f"  Warnings: {', '.join(warned)}")
        else:
            failed = [c.name for c in self.checks if not c.passed]
            hard = [c.name for c in self.checks if not c.passed and c.name in HARD_CHECKS]
            print(f"  \033[91mOVERALL: FAIL — {len(failed)} check(s) failed\033[0m")
            print(f"  Failed: {', '.join(failed)}  (hard: {', '.join(hard)})")
        print("=" * 70 + "\n")


