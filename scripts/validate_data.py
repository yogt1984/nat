def validate(data_dir: Path, config: ValidationConfig, hours: Optional[int] = None,
             quiet: bool = False) -> ValidationReport:
    """Run all validation checks. ``quiet`` suppresses progress prints (for --json)."""
    def _say(msg):
        if not quiet:
            print(msg)

    _say(f"\n  Scanning {data_dir}...")

    # Find files
    files = find_parquet_files(data_dir, hours)
    _say(f"  Found {len(files)} Parquet file(s)")

    if not files:
        return ValidationReport(
            data_dir=str(data_dir),
            timestamp=datetime.now(),
            total_files=0,
            total_rows=0,
            symbols=[],
            date_range=(None, None),
            checks=[CheckResult(
                name="Data Presence",
                passed=False,
                message="No Parquet files found"
            )]
        )

    # Load data
    _say("  Loading data...")
    df = load_data(files)
    _say(f"  Loaded {len(df):,} rows")

    # Extract metadata
    symbols = sorted(df['symbol'].unique().tolist()) if not df.empty else []

    if not df.empty:
        try:
            ts_col = get_timestamp_col(df)
            min_ts = pd.Timestamp(df[ts_col].min(), unit='ns')
            max_ts = pd.Timestamp(df[ts_col].max(), unit='ns')
            date_range = (min_ts.strftime('%Y-%m-%d %H:%M'), max_ts.strftime('%Y-%m-%d %H:%M'))
        except (ValueError, KeyError):
            date_range = (None, None)
    else:
        date_range = (None, None)

    # Run checks
    _say("  Running validation checks...")
    checks = [
        check_file_integrity(files),
        check_continuity(df, config),
        check_nan_ratio(df, config),
        check_category_liveness(df, config),
        check_feature_ranges(df, config),
        check_cross_symbol_consistency(df, config),
        check_data_rate(df, config),
        check_sequence_monotonicity(df),
    ]

    return ValidationReport(
        data_dir=str(data_dir),
        timestamp=datetime.now(),
        total_files=len(files),
        total_rows=len(df),
        symbols=symbols,
        date_range=date_range,
        checks=checks
    )


