def check_file_integrity(files: list) -> CheckResult:
    """Check that all Parquet files are readable."""
    errors = []
    for f in files:
        try:
            pq.read_table(f)
        except Exception as e:
            errors.append(f"{f.name}: {e}")

    if errors:
        return CheckResult(
            name="File Integrity",
            passed=False,
            message=f"{len(errors)} file(s) failed to read",
            details={"errors": errors[:5]}  # Show first 5
        )

    return CheckResult(
        name="File Integrity",
        passed=True,
        message=f"All {len(files)} files readable"
    )


def get_timestamp_col(df: pd.DataFrame) -> str:
    """Get the timestamp column name (handles schema variations)."""
    if 'timestamp_ns' in df.columns:
        return 'timestamp_ns'
    elif 'timestamp' in df.columns:
        return 'timestamp'
    else:
        raise ValueError("No timestamp column found")


def check_continuity(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Check for gaps in timestamps."""
    if df.empty:
        return CheckResult(
            name="Continuity",
            passed=False,
            message="No data to check"
        )

    ts_col = get_timestamp_col(df)

    # Sort by timestamp
    df_sorted = df.sort_values(ts_col)

    # Calculate gaps per symbol
    gap_info = {}
    max_gap = 0
    total_gaps = 0

    for symbol in df['symbol'].unique():
        sym_df = df_sorted[df_sorted['symbol'] == symbol]
        timestamps = sym_df[ts_col].values

        if len(timestamps) < 2:
            continue

        # Calculate gaps in seconds
        gaps = np.diff(timestamps) / 1e9
        large_gaps = gaps[gaps > config.max_gap_seconds]

        if len(large_gaps) > 0:
            gap_info[symbol] = {
                'count': len(large_gaps),
                'max_gap': float(np.max(large_gaps)),
                'avg_gap': float(np.mean(large_gaps))
            }
            max_gap = max(max_gap, np.max(large_gaps))
            total_gaps += len(large_gaps)

    if total_gaps > 0:
        return CheckResult(
            name="Continuity",
            passed=False,
            message=f"{total_gaps} gaps > {config.max_gap_seconds}s detected (max: {max_gap:.1f}s)",
            details=gap_info
        )

    return CheckResult(
        name="Continuity",
        passed=True,
        message=f"No gaps > {config.max_gap_seconds}s detected"
    )


def check_nan_ratio(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Check NaN ratio in feature columns."""
    if df.empty:
        return CheckResult(
            name="NaN Ratio",
            passed=False,
            message="No data to check"
        )

    # Skip metadata columns
    meta_cols = ['timestamp_ns', 'timestamp', 'symbol', 'sequence_id']
    feature_cols = [c for c in df.columns if c not in meta_cols]

    # Filter out warmup period
    try:
        ts_col = get_timestamp_col(df)
        min_ts = df[ts_col].min()
        warmup_cutoff = min_ts + (config.warmup_seconds * 1e9)
        df_post_warmup = df[df[ts_col] >= warmup_cutoff]
    except (ValueError, KeyError):
        df_post_warmup = df

    if df_post_warmup.empty:
        return CheckResult(
            name="NaN Ratio",
            passed=True,
            message="Insufficient data after warmup filter"
        )

    # Calculate NaN ratio per column
    nan_ratios = {}
    high_nan_cols = []

    for col in feature_cols:
        if col in df_post_warmup.columns:
            ratio = df_post_warmup[col].isna().mean()
            if ratio > config.max_nan_ratio:
                nan_ratios[col] = f"{ratio:.2%}"
                high_nan_cols.append(col)

    overall_nan = df_post_warmup[feature_cols].isna().mean().mean()

    if high_nan_cols:
        return CheckResult(
            name="NaN Ratio",
            passed=False,
            message=f"{len(high_nan_cols)} columns exceed {config.max_nan_ratio:.0%} NaN threshold",
            details={"columns": nan_ratios}
        )

    return CheckResult(
        name="NaN Ratio",
        passed=True,
        message=f"Overall NaN ratio: {overall_nan:.2%} (threshold: {config.max_nan_ratio:.0%})"
    )


#: Columns that are not features and must never be scored as a category.
_META_COLS = ('timestamp_ns', 'timestamp', 'symbol', 'sequence_id')


#: Prefixes that belong to one manifest category but do not share a common stem.
#: Concentration is the only such case: its 15 columns are named after the statistic
#: (`gini`, `theil`, `herfindahl`, `top5`, …) rather than carrying a `conc_` prefix, so
#: splitting on the first `_` shatters one category into fourteen singletons and every
#: one of them reads as "a dead category". Found by real-parquet smoke, which is the
#: only place it could have been found — the planted frames use tidy prefixes.
_CONCENTRATION_PREFIXES = frozenset({
    'concentration', 'active', 'positions', 'position', 'largest', 'nearest',
    'top5', 'top10', 'top20', 'top50', 'herfindahl', 'gini', 'theil', 'hhi',
})


def _category_of(column: str) -> str:
    """The feature category a column belongs to, per `FEATURES.md`'s 21 categories.

    Mostly the prefix up to the first `_` (`raw_`, `imbalance_`, `regime_`, `hm_`, …),
    with concentration's statistic-named columns folded back into one category.
    """
    stem = column.split('_', 1)[0]
    return 'concentration' if stem in _CONCENTRATION_PREFIXES else stem


def check_category_liveness(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Flag whole feature CATEGORIES that are 100% NaN (BUG-6).

    `NaN Ratio` already reports dead columns, but it reports them one per line: on
    2026-08-08 it said "90 columns exceed 1% NaN threshold" — the same sentence it
    printed on 2026-07-15, when the `regime_` category was still alive. A message that
    does not change when a 23-feature subsystem dies cannot raise the alarm, and BUG-6
    went unnoticed for 13 days behind exactly that sentence.

    So this check works at the category level, where the signal survives: 90 flagged
    columns collapse to one named item. A category is dead only when *every* one of its
    columns is wholly NaN — partial deadness is noise and belongs to `NaN Ratio`.

    There is deliberately no warmup grace. A category NaN for an entire file never
    started; warmup shows up as a leading NaN block, not a column of them.
    """
    if df.empty:
        return CheckResult(
            name="Category Liveness",
            passed=False,
            message="No data to check",
        )

    feature_cols = [c for c in df.columns if c not in _META_COLS]
    categories: dict[str, dict[str, int]] = {}
    for col in feature_cols:
        cat = _category_of(col)
        entry = categories.setdefault(cat, {"dead": 0, "total": 0})
        entry["total"] += 1
        series = pd.to_numeric(df[col], errors="coerce")
        if not np.isfinite(series.to_numpy(dtype=float)).any():
            entry["dead"] += 1

    wholly_dead = sorted(
        cat for cat, e in categories.items()
        if e["total"] > 0 and e["dead"] == e["total"]
    )
    undeclared = [c for c in wholly_dead if c not in config.expected_dead_categories]
    declared = [c for c in wholly_dead if c in config.expected_dead_categories]

    details = {
        "categories": categories,
        "dead_categories": undeclared,
        "declared_dead": declared,
    }

    if undeclared:
        named = ", ".join(
            f"{c} ({categories[c]['total']} features)" for c in undeclared
        )
        return CheckResult(
            name="Category Liveness",
            passed=False,
            message=f"{len(undeclared)} feature category(ies) wholly NaN: {named}",
            details=details,
        )

    suffix = f" ({len(declared)} declared-dead: {', '.join(declared)})" if declared else ""
    return CheckResult(
        name="Category Liveness",
        passed=True,
        message=f"All {len(categories) - len(declared)} live categories producing values{suffix}",
        details=details,
    )


def check_feature_ranges(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Check that key features are within expected ranges."""
    if df.empty:
        return CheckResult(
            name="Feature Ranges",
            passed=False,
            message="No data to check"
        )

    out_of_range = {}

    for feature, (min_val, max_val) in config.feature_ranges.items():
        if feature not in df.columns:
            continue

        values = df[feature].dropna()
        if len(values) == 0:
            continue

        below = (values < min_val).sum()
        above = (values > max_val).sum()

        if below > 0 or above > 0:
            out_of_range[feature] = {
                'below_min': int(below),
                'above_max': int(above),
                'actual_range': f"[{values.min():.4g}, {values.max():.4g}]",
                'expected': f"[{min_val}, {max_val}]"
            }

    if out_of_range:
        return CheckResult(
            name="Feature Ranges",
            passed=False,
            message=f"{len(out_of_range)} features outside expected range",
            details=out_of_range
        )

    return CheckResult(
        name="Feature Ranges",
        passed=True,
        message=f"All {len(config.feature_ranges)} monitored features within range"
    )


def check_cross_symbol_consistency(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Check that all symbols have similar row counts."""
    if df.empty:
        return CheckResult(
            name="Cross-Symbol Consistency",
            passed=False,
            message="No data to check"
        )

    counts = df.groupby('symbol').size()

    if len(counts) < 2:
        return CheckResult(
            name="Cross-Symbol Consistency",
            passed=True,
            message=f"Only {len(counts)} symbol(s), skipping comparison"
        )

    max_count = counts.max()
    min_count = counts.min()
    ratio_diff = (max_count - min_count) / max_count

    details = {sym: int(cnt) for sym, cnt in counts.items()}
    details['ratio_diff'] = f"{ratio_diff:.1%}"

    if ratio_diff > config.max_count_ratio_diff:
        return CheckResult(
            name="Cross-Symbol Consistency",
            passed=False,
            message=f"Row count varies by {ratio_diff:.1%} (threshold: {config.max_count_ratio_diff:.0%})",
            details=details
        )

    return CheckResult(
        name="Cross-Symbol Consistency",
        passed=True,
        message=f"Row counts consistent across symbols (diff: {ratio_diff:.1%})",
        details=details
    )


def check_data_rate(df: pd.DataFrame, config: ValidationConfig) -> CheckResult:
    """Check that data rate meets expectations."""
    if df.empty:
        return CheckResult(
            name="Data Rate",
            passed=False,
            message="No data to check"
        )

    ts_col = get_timestamp_col(df)

    # Calculate time span
    min_ts = df[ts_col].min()
    max_ts = df[ts_col].max()
    duration_hours = (max_ts - min_ts) / 1e9 / 3600

    if duration_hours < 0.1:
        return CheckResult(
            name="Data Rate",
            passed=True,
            message=f"Insufficient duration ({duration_hours:.2f}h) for rate check"
        )

    # Check rate per symbol
    rate_info = {}
    low_rate_symbols = []

    for symbol in df['symbol'].unique():
        sym_count = len(df[df['symbol'] == symbol])
        rate_per_hour = sym_count / duration_hours
        rate_info[symbol] = f"{rate_per_hour:.0f}/hour"

        if rate_per_hour < config.min_records_per_hour:
            low_rate_symbols.append(symbol)

    rate_info['duration_hours'] = f"{duration_hours:.2f}"

    if low_rate_symbols:
        return CheckResult(
            name="Data Rate",
            passed=False,
            message=f"{len(low_rate_symbols)} symbol(s) below {config.min_records_per_hour}/hour",
            details=rate_info
        )

    return CheckResult(
        name="Data Rate",
        passed=True,
        message=f"All symbols meet minimum rate ({config.min_records_per_hour}/hour)",
        details=rate_info
    )


def check_sequence_monotonicity(df: pd.DataFrame) -> CheckResult:
    """Check that sequence IDs are monotonically increasing per symbol."""
    if df.empty:
        return CheckResult(
            name="Sequence Monotonicity",
            passed=False,
            message="No data to check"
        )

    # Check if sequence_id column exists
    if 'sequence_id' not in df.columns:
        return CheckResult(
            name="Sequence Monotonicity",
            passed=True,
            message="No sequence_id column (older schema), skipping"
        )

    issues = {}

    for symbol in df['symbol'].unique():
        ts_col = get_timestamp_col(df)
        sym_df = df[df['symbol'] == symbol].sort_values(ts_col)
        seq_ids = sym_df['sequence_id'].dropna().values

        if len(seq_ids) < 2:
            continue

        # Check for non-increasing sequences
        diffs = np.diff(seq_ids)
        non_increasing = (diffs <= 0).sum()

        if non_increasing > 0:
            issues[symbol] = {
                'non_increasing_count': int(non_increasing),
                'first_seq': int(seq_ids[0]),
                'last_seq': int(seq_ids[-1])
            }

    if issues:
        return CheckResult(
            name="Sequence Monotonicity",
            passed=False,
            message=f"{len(issues)} symbol(s) have non-monotonic sequences",
            details=issues
        )

    return CheckResult(
        name="Sequence Monotonicity",
        passed=True,
        message="All sequences monotonically increasing"
    )


